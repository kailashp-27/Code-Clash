// Isolated headless browser QA of the real running app; never reads an existing browser profile.
// Pass the installed tool bundle's node_modules directory as the first argument.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const root = path.resolve(__dirname, '..');
if (!process.argv[2]) throw new Error('Pass the installed browser tooling node_modules directory.');
const { chromium } = createRequire(path.join(path.resolve(process.argv[2]), 'package.json'))('playwright');
const fixture = JSON.parse(fs.readFileSync(path.join(root, '.cache/battle-demo.json'), 'utf8'));
const base = 'http://127.0.0.1:5173';
async function login(page, account) {
  await page.goto(base + '/login');
  await page.getByPlaceholder('you@example.com').fill(account.email);
  await page.getByPlaceholder('••••••••').fill(account.password);
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await page.waitForURL('**/profile');
}
async function main() {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await login(page, fixture.accounts[0]);
    await page.getByRole('navigation', { name: 'Profile actions' }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Sign out', exact: true }).count(), 1);
    await page.screenshot({ path: path.join(root, 'docs/profile-navigation-updated.jpg'), animations: 'disabled' });
    await page.getByRole('link', { name: 'Return to lobby', exact: true }).click();
    await page.waitForURL(base + '/');
    await page.goto(base + '/battle/' + fixture.matchId);
    await page.getByRole('heading', { name: 'Arena conquered.', exact: true }).waitFor();
    await page.getByText('+16', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(root, 'docs/battle-result-demo.jpg'), fullPage: true, animations: 'disabled' });
    await page.getByRole('button', { name: 'Review your code', exact: true }).click();
    const editor = page.getByRole('textbox', { name: 'Balanced Brackets solution in JavaScript', exact: true });
    await editor.waitFor();
    await page.getByText('// Controlled demonstration: generated by Codex for this test match.', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(root, 'docs/battle-code-review-demo.jpg'), animations: 'disabled' });
    await page.getByRole('button', { name: 'Back to result', exact: true }).click();
    await page.getByRole('heading', { name: 'Arena conquered.', exact: true }).waitFor();
    await page.getByText('Report a concern', { exact: false }).click();
    await page.getByRole('combobox', { name: 'Opponent submission' }).waitFor();
    assert.ok((await page.getByRole('combobox', { name: 'Opponent submission' }).textContent()).includes('Reported (pending)'));
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(root, 'docs/battle-result-mobile-demo.jpg'), fullPage: true, animations: 'disabled' });
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth + 1);
    assert.equal(overflow, false, 'Mobile result should not scroll horizontally');
    await page.goto(base + '/profile');
    await page.getByRole('button', { name: 'Sign out', exact: true }).click();
    await page.waitForURL(base + '/');
    assert.equal(await page.evaluate(() => localStorage.getItem('token')), null);
    assert.equal(await page.evaluate(() => localStorage.getItem('user')), null);
    await page.goto(base + '/profile');
    await page.waitForURL('**/login');
    const subject = await browser.newContext({ viewport: { width: 1280, height: 720 } });
    const subjectPage = await subject.newPage();
    await login(subjectPage, fixture.accounts[1]);
    await subjectPage.goto(base + '/battle/' + fixture.matchId);
    await subjectPage.getByRole('heading', { name: 'Your next move awaits.', exact: true }).waitFor();
    assert.ok((await subjectPage.locator('.result-player--winner').textContent()).includes(fixture.accounts[0].username), 'Highlight the actual winner for both players');
    await subjectPage.goto(base + '/standing');
    await subjectPage.getByRole('heading', { name: 'Account in good standing' }).waitFor();
    await subjectPage.getByText('pending', { exact: true }).waitFor();
    const moderatorEmail = process.env.DEMO_MODERATOR_EMAIL;
    const moderatorPassword = process.env.DEMO_MODERATOR_PASSWORD;
    if (moderatorEmail || moderatorPassword) {
      assert.ok(moderatorEmail && moderatorPassword, 'Set both DEMO_MODERATOR_EMAIL and DEMO_MODERATOR_PASSWORD for optional moderator QA');
      const moderator = await browser.newContext({ viewport: { width: 1280, height: 720 } });
      const moderatorPage = await moderator.newPage();
      await login(moderatorPage, { email: moderatorEmail, password: moderatorPassword });
      await moderatorPage.goto(base + '/moderation');
      await moderatorPage.getByRole('heading', { name: fixture.accounts[1].username, exact: true }).waitFor();
      await moderatorPage.getByRole('button', { name: 'Confirm violation', exact: true }).waitFor();
      await moderatorPage.screenshot({ path: path.join(root, 'docs/battle-moderation-demo.jpg'), fullPage: true, animations: 'disabled' });
      console.log('PASS optional moderator queue. No report was confirmed.');
    }
    assert.deepEqual(errors, [], 'Battle page must render without uncaught errors');
    console.log('PASS actual browser: profile lobby navigation, sign out and protected-route redirect; victory/Elo, saved-source review and back navigation, pending report, mobile layout and account standing. Screenshots saved in docs/.');
  } finally { await browser.close(); }
}
main().catch(e => { console.error(e.message); process.exitCode = 1; });
